# -*- coding: utf-8 -*-
"""生成手机专用轻量数据：data/m_words.js、data/m_units.js

源：data/words.js、data/units.js（均为 tools/build_js.py 的生成物，禁止手写）
产出同时写入本项目 data/ 与同级部署包 ../WordGrove/data/。
网站运行时不依赖本脚本；词库更新后重跑一次即可。
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "data")
OUT_DIRS = [
    SRC,
    os.path.normpath(os.path.join(ROOT, "..", "WordGrove", "data")),
]


def load(fname):
    text = open(os.path.join(SRC, fname), encoding="utf-8").read()
    return json.loads(text[text.index("=") + 1:].strip().rstrip(";"))


def jsafe(obj):
    out = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    return out.replace(u"\u2028", "\\u2028").replace(u"\u2029", "\\u2029")


def slim_word(w):
    d = {
        "w": w.get("w", ""),
        "z": w.get("zh") or w.get("mean") or "",
        "p": w.get("ipa", ""),
        "l": w.get("level", "cet4"),
    }
    if w.get("core"):
        d["c"] = 1
    ex = w.get("ex")
    if ex and ex.get("en"):
        d["e"] = ex["en"]
        if ex.get("src"):
            d["s"] = ex["src"]
    if w.get("exZh"):
        d["x"] = w["exZh"]
    return d


def slim_unit(u):
    texts = []
    for t in u.get("texts", []):
        texts.append({
            "id": t.get("id", ""),
            "label": t.get("label", ""),
            "title": t.get("title", ""),
            "subtitle": t.get("subtitle", ""),
            "paras": t.get("paragraphs", []),
        })
    return {"id": u.get("id", ""), "title": u.get("title", ""),
            "cn": u.get("cn", ""), "texts": texts}


def emit(fname, varname, obj, note):
    payload = ("/* generated by tools/build_mobile_data.py - do not edit by hand */\n"
               "/* %s */\nwindow.%s=%s;\n" % (note, varname, jsafe(obj)))
    for d in OUT_DIRS:
        if not os.path.isdir(d):
            continue
        path = os.path.join(d, fname)
        open(path, "w", encoding="utf-8").write(payload)
        print("%-24s %9d bytes  -> %s" % (fname, len(payload.encode("utf-8")), path))


def main():
    words = load("words.js")
    units = load("units.js")
    emit("m_words.js", "CILIN_M_WORDS", [slim_word(w) for w in words],
         "%d entries; slim index for the mobile reader" % len(words))
    emit("m_units.js", "CILIN_M_UNITS", [slim_unit(u) for u in units],
         "%d units; loaded on demand by the reading tab" % len(units))


if __name__ == "__main__":
    main()
